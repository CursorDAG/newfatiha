async function main() {
  const chapters = await prisma.bookChapter.findMany({ where: { bookId: BOOK_ID } });
  let patched = 0;
  for (const ch of chapters) {
    const ru = RU[ch.number];
    if (!ru) continue;
    await prisma.bookChapter.update({
      where: { id: ch.id },
      data: { title: `${ch.number}. ${ru}` },
    });
    patched++;
  }
  console.log(`✅ Обновлено названий разделов: ${patched}/${chapters.length}`);
}

main()
  .catch((e) => {
    console.error("❌", e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
